RE = re.compile(r"^>\s*\*\*一句话结论\*\*[：:]\s*(.+?)\s*$", re.M)


def main():
    notes = sorted(ROOT.glob("[0-9][0-9]_*_系统笔记.md"))
    if len(notes) != 47:
        sys.exit(f"扫描到 {len(notes)} 篇，预期 47 篇")

    over, n_change = [], 0
    # 先自检：新文本本身不得超限，且不得含 LaTeX（避免字数判虚高）
    for no, t in TIGHTENED.items():
        if len(t) > MAX:
            over.append(f"  配置 {no} 篇新结论 {len(t)} 字 > {MAX}")
        if "$" in t:
            over.append(f"  配置 {no} 篇新结论含 LaTeX，应改用 Unicode")

    for p in notes:
        no = p.name[:2]
        text = p.read_text(encoding="utf-8")
        m = RE.search(text)
        if not m:
            print(f"  ! {p.name} 无一句话结论，跳过")
            continue
        cur = m.group(1)
        if no not in TIGHTENED:
            if len(cur) > MAX:
                over.append(f"  {p.name} 未配置新文本且当前 {len(cur)} 字超限")
            continue
        new = TIGHTENED[no]
        if cur == new:
            continue
        n_change += 1
        print(f"  · {p.name}：{len(cur)} 字 -> {len(new)} 字")
        if not DRY:
            p.write_text(
                text[: m.start(1)] + new + text[m.end(1):], encoding="utf-8"
            )

    if over:
        print("\n✗ 仍有超限项，未通过自检：")
        print("\n".join(over))
        sys.exit(1)
    print(f"\n完成：收紧 {n_change} 篇，全部 ≤{MAX} 字"
          f"{'（dry-run，未写盘）' if DRY else ''}")


if __name__ == "__main__":
    main()
